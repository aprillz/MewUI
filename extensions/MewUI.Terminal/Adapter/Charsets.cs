    /// <summary>Builds a table of <paramref name="size"/> characters from <paramref name="baseChar"/>, with replacements.</summary>
    private static string Build(int baseChar, int size, (int From, int To)[] replacements)
    {
        var table = new char[size];
        for (int index = 0; index < size; index++)
        {
            table[index] = (char)(baseChar + index);
        }

        foreach (var (from, to) in replacements)
        {
            table[from - baseChar] = (char)to;
        }

        return new string(table);
    }
