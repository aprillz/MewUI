using System.Collections.Generic;
using System.Text;

namespace Aprillz.MewUI.Generators;

/// <summary>Writes one extension class source for an owner.</summary>
internal static class FluentExtensionEmitter
{
    private const string GETS_OR_SETS = "Gets or sets ";
    private const string GETS = "Gets ";
    private const string RETURNS = "The same element for chaining.";

    public static string Emit(
        FluentOwnerModel owner,
        string ownerNamespace,
        IReadOnlyList<FluentMemberModel> members,
        IReadOnlyList<string> skipped)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable CS0618, CS0612");
        foreach (var entry in skipped)
        {
            builder.Append("// Skipped ").AppendLine(entry);
        }

        builder.AppendLine();

        string indent = string.Empty;
        if (ownerNamespace.Length > 0)
        {
            builder.Append("namespace ").AppendLine(ownerNamespace);
            builder.AppendLine("{");
            indent = "    ";
        }

        builder.Append(indent).Append("/// <summary>Generated fluent setters and event subscriptions for <see cref=\"").Append(owner.Cref).AppendLine("\"/>.</summary>");
        builder.Append(indent).AppendLine("[global::System.Diagnostics.DebuggerStepThrough]");
        builder.Append(indent).Append("public static partial class ").AppendLine(owner.ClassName);
        builder.Append(indent).AppendLine("{");

        for (int index = 0; index < members.Count; index++)
        {
            if (index > 0)
            {
                builder.AppendLine();
            }

            AppendMethod(builder, indent + "    ", owner, members[index]);
        }

        builder.Append(indent).AppendLine("}");
        if (ownerNamespace.Length > 0)
        {
            builder.AppendLine("}");
        }

        return builder.ToString();
    }

    private static void AppendMethod(StringBuilder builder, string indent, FluentOwnerModel owner, FluentMemberModel member)
    {
        string memberCref = owner.Cref + "." + member.Name;
        string parameterName = member.IsEvent ? "handler" : "value";

        builder.Append(indent).Append("/// <summary>").Append(Summary(member, memberCref)).AppendLine("</summary>");
        if (!owner.IsSealed && !owner.IsGeneric)
        {
            builder.Append(indent).AppendLine("/// <typeparam name=\"T\">Receiver type.</typeparam>");
        }

        builder.Append(indent).Append("/// <param name=\"target\">Target <see cref=\"").Append(owner.Cref).AppendLine("\"/>.</param>");
        builder.Append(indent).Append("/// <param name=\"").Append(parameterName).Append("\">")
            .Append(member.IsEvent ? "Handler subscribed to <see cref=\"" : "Value assigned to <see cref=\"")
            .Append(memberCref).AppendLine("\"/>.</param>");
        builder.Append(indent).Append("/// <returns>").Append(RETURNS).AppendLine("</returns>");

        string receiverType;
        string typeParameters;
        string constraints;
        if (owner.IsSealed || owner.IsGeneric)
        {
            receiverType = owner.Display;
            typeParameters = owner.TypeParameterList;
            constraints = owner.ConstraintClauses;
        }
        else
        {
            receiverType = "T";
            typeParameters = "<T>";
            constraints = " where T : " + owner.Display;
        }

        string parameter = member.IsDelegate && !member.IsEvent
            ? "[global::Aprillz.MewUI.FluentSetsMember(\"" + member.Name + "\")] " + member.TypeDisplay + " " + parameterName
            : member.TypeDisplay + " " + parameterName + (member.IsBool ? " = true" : string.Empty);

        builder.Append(indent).Append("public static ").Append(receiverType).Append(' ').Append(member.MethodName).Append(typeParameters)
            .Append("(this ").Append(receiverType).Append(" target, ").Append(parameter).Append(')').AppendLine(constraints);
        builder.Append(indent).AppendLine("{");
        builder.Append(indent).Append("    target.").Append(member.Name).Append(member.IsEvent ? " += " : " = ").Append(parameterName).AppendLine(";");
        builder.Append(indent).AppendLine("    return target;");
        builder.Append(indent).AppendLine("}");
    }

    private static string Summary(FluentMemberModel member, string memberCref)
    {
        string text = member.SummaryXml;
        if (member.IsEvent)
        {
            string subscribes = "Subscribes <paramref name=\"handler\"/> to <see cref=\"" + memberCref + "\"/>.";
            return text.Length == 0 ? subscribes : subscribes + " " + text;
        }

        if (text.StartsWith(GETS_OR_SETS, System.StringComparison.Ordinal))
        {
            return "Sets " + text.Substring(GETS_OR_SETS.Length);
        }

        if (text.StartsWith(GETS, System.StringComparison.Ordinal))
        {
            return "Sets " + text.Substring(GETS.Length);
        }

        string sets = "Sets <see cref=\"" + memberCref + "\"/>.";
        return text.Length == 0 ? sets : sets + " " + text;
    }
}
