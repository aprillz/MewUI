using System.Security.Cryptography;
using System.Text;
using Aprillz.MewUI.MarkupAudit;

namespace MewUI.Test.Markup;

/// <summary>Checks the Starlight pass over a small xmldocmd-shaped tree: frontmatter, slugs, link rewriting, guide lines, and idempotence.</summary>
[TestClass]
public sealed class ApiStarlightWriterTests
{
    private const string SITE_BASE = "/MewUI";
    private const string VERSION_LINE = "Generated from MewUI 1.2.3, commit `abcdef01`.";

    private string _root = string.Empty;

    [TestInitialize]
    public void CreateTree()
    {
        _root = Path.Combine(Path.GetTempPath(), $"mewui-starlight-{Guid.NewGuid():N}");
        var controls = Path.Combine(_root, "Aprillz.MewUI", "Aprillz.MewUI.Controls");
        Directory.CreateDirectory(Path.Combine(controls, "Button"));

        WritePage("version.txt", "MewUIVersion=1.2.3\nCommit=abcdef0123456789\n");
        WritePage("index.md",
            "---\ntitle: API Reference\nsidebar:\n  order: 0\n---\n\n# MewUI API Reference\n\n" +
            "| Package | Assembly |\n| --- | --- |\n| `Aprillz.MewUI.Core` | [Aprillz.MewUI](Aprillz.MewUI/index.md) |\n");
        WritePage("Aprillz.MewUI/index.md",
            "---\ntitle: Aprillz.MewUI\nsidebar:\n  order: 1\n---\n\n# Aprillz.MewUI\n\n" +
            "| Type | Kind |\n| --- | --- |\n| [Button](Aprillz.MewUI.Controls/Button.md) | class |\n");
        WritePage("Aprillz.MewUI/Aprillz.MewUI.Controls/Button.md",
            "# Button class\n\nA button control that responds to clicks.\n\n```csharp\npublic class Button : CommandSourceControl\n```\n\n" +
            "## Public Members\n\n| name | description |\n| --- | --- |\n| event [Click](Button/Click.md) | Occurs when the button is clicked. |\n\n" +
            "## See Also\n\n* class [CommandSourceControl](./CommandSourceControl.md)\n* namespace [Aprillz.MewUI.Controls](../Aprillz.MewUI.md)\n\n" +
            "<!-- DO NOT EDIT: generated by xmldocmd for Aprillz.MewUI.dll -->\n");
        WritePage("Aprillz.MewUI/Aprillz.MewUI.Controls/Grid.md",
            "# Grid class\n\nA grid panel.\n\n```csharp\npublic class Grid : Panel\n```\n\n<!-- DO NOT EDIT: generated by xmldocmd for Aprillz.MewUI.dll -->\n");
        WritePage("Aprillz.MewUI/Aprillz.MewUI.Controls/Button/Click.md",
            "# Button.Click event\n\nOccurs when the button is clicked.\n\n```csharp\npublic event Action? Click;\n```\n\n" +
            "Fluent: [`.OnClick(Action)`](../ButtonMarkupExtensions/OnClick.md)\n\n" +
            "## See Also\n\n* class [Button](../Button.md)\n* namespace [Aprillz.MewUI.Controls](../../Aprillz.MewUI.md)\n\n" +
            "<!-- DO NOT EDIT: generated by xmldocmd for Aprillz.MewUI.dll -->\n");
        WritePage("guide-links.json",
            "{\n  \"Aprillz.MewUI.Controls.Button\": \"/markup/button/\",\n  \"Aprillz.MewUI.Controls.\": \"/csharpmarkup/\"\n}\n");
    }

    [TestCleanup]
    public void DeleteTree()
    {
        if (Directory.Exists(_root))
        {
            Directory.Delete(_root, true);
        }
    }

    [TestMethod]
    public void Run_AddsFrontMatterAndRewritesLinks()
    {
        var warnings = new List<string>();
        var summary = ApiStarlightWriter.Run(_root, SITE_BASE, Path.Combine(_root, "guide-links.json"), warnings);

        Assert.IsEmpty(warnings, string.Join("\n", warnings));
        Assert.AreEqual(5, summary.Pages);
        Assert.AreEqual(3, summary.FrontMatterAdded);
        Assert.AreEqual(0, summary.UnresolvedLinks);

        var button = ReadPage("Aprillz.MewUI/Aprillz.MewUI.Controls/Button.md");
        StringAssert.StartsWith(button, "---\ntitle: \"Button class\"\nslug: api/aprillz.mewui/aprillz.mewui.controls/button\n---\n\nA button control that responds to clicks.\n\nGuide: [C# Markup reference: Button](/MewUI/markup/button/)\n\n```csharp\n");
        Assert.IsFalse(button.Contains("# Button class", StringComparison.Ordinal), "the heading becomes the title");
        StringAssert.Contains(button, "[Click](/MewUI/api/aprillz.mewui/aprillz.mewui.controls/button/click/)");
        StringAssert.Contains(button, "[CommandSourceControl](/MewUI/api/aprillz.mewui/aprillz.mewui.controls/commandsourcecontrol/)");
        StringAssert.Contains(button, "[Aprillz.MewUI.Controls](/MewUI/api/aprillz.mewui/aprillz.mewui/)");
        Assert.IsFalse(button.Contains("DO NOT EDIT", StringComparison.Ordinal), "the generator comment is removed");
        Assert.IsFalse(button.Contains(".md)", StringComparison.Ordinal), "no relative page link remains");

        var click = ReadPage("Aprillz.MewUI/Aprillz.MewUI.Controls/Button/Click.md");
        StringAssert.StartsWith(click, "---\ntitle: \"Button.Click event\"\nslug: api/aprillz.mewui/aprillz.mewui.controls/button/click\n---\n");
        StringAssert.Contains(click, "Fluent: [`.OnClick(Action)`](/MewUI/api/aprillz.mewui/aprillz.mewui.controls/buttonmarkupextensions/onclick/)");
        StringAssert.Contains(click, "[Button](/MewUI/api/aprillz.mewui/aprillz.mewui.controls/button/)");
        Assert.IsFalse(click.Contains("Guide: ", StringComparison.Ordinal), "member pages get no guide line");

        var grid = ReadPage("Aprillz.MewUI/Aprillz.MewUI.Controls/Grid.md");
        StringAssert.Contains(grid, "A grid panel.\n\nGuide: [C# Markup guide](/MewUI/csharpmarkup/)\n\n```csharp\n");

        var rootIndex = ReadPage("index.md");
        StringAssert.StartsWith(rootIndex, "---\ntitle: API Reference\nslug: api\nsidebar:\n  order: 0\n---\n\n" + VERSION_LINE + "\n\n| Package |");
        StringAssert.Contains(rootIndex, "[Aprillz.MewUI](/MewUI/api/aprillz.mewui/)");

        var assemblyIndex = ReadPage("Aprillz.MewUI/index.md");
        StringAssert.StartsWith(assemblyIndex, "---\ntitle: Aprillz.MewUI\nslug: api/aprillz.mewui\nsidebar:\n  order: 1\n---\n\n| Type |");
        Assert.IsFalse(assemblyIndex.Contains("\n# ", StringComparison.Ordinal), "the H1 duplicates the frontmatter title");
        StringAssert.Contains(assemblyIndex, "[Button](/MewUI/api/aprillz.mewui/aprillz.mewui.controls/button/)");
        Assert.AreEqual(1, CountOccurrences(assemblyIndex, "title:"), "existing frontmatter is kept");
        Assert.IsFalse(assemblyIndex.Contains(VERSION_LINE, StringComparison.Ordinal), "only the root index is stamped");
    }

    [TestMethod]
    public void Run_IsIdempotent()
    {
        var guideLinks = Path.Combine(_root, "guide-links.json");
        ApiStarlightWriter.Run(_root, SITE_BASE, guideLinks, new List<string>());
        var firstHash = HashTree();

        var summary = ApiStarlightWriter.Run(_root, SITE_BASE, guideLinks, new List<string>());

        Assert.AreEqual(firstHash, HashTree());
        Assert.AreEqual(0, summary.FrontMatterAdded);
        Assert.AreEqual(0, summary.LinksRewritten);
        Assert.AreEqual(1, CountOccurrences(ReadPage("index.md"), VERSION_LINE));
        Assert.AreEqual(1, CountOccurrences(ReadPage("Aprillz.MewUI/Aprillz.MewUI.Controls/Button.md"), "Guide: "));
    }

    [TestMethod]
    public void Run_DropsLeadingHeadingOfFrontMatterPagesOnce()
    {
        WritePage("Aprillz.MewUI/Aprillz.MewUI/Application/SetAccent.md",
            "# Application.SetAccent method (1 of 2)\n\nSets a built-in accent.\n\n---\n\n# Application.SetAccent method (2 of 2)\n\nSets a custom accent.\n");

        ApiStarlightWriter.Run(_root, SITE_BASE, null, new List<string>());
        var firstRootIndex = ReadPage("index.md");
        var firstOverloads = ReadPage("Aprillz.MewUI/Aprillz.MewUI/Application/SetAccent.md");
        ApiStarlightWriter.Run(_root, SITE_BASE, null, new List<string>());

        Assert.IsFalse(firstRootIndex.Contains("# MewUI API Reference", StringComparison.Ordinal), "the H1 under the frontmatter is dropped");
        Assert.AreEqual(1, CountOccurrences(firstRootIndex, VERSION_LINE));
        Assert.AreEqual(firstRootIndex, ReadPage("index.md"));
        StringAssert.StartsWith(firstOverloads, "---\ntitle: \"Application.SetAccent method (1 of 2)\"\n");
        StringAssert.Contains(firstOverloads, "\n# Application.SetAccent method (2 of 2)\n");
        Assert.AreEqual(firstOverloads, ReadPage("Aprillz.MewUI/Aprillz.MewUI/Application/SetAccent.md"), "a later overload heading is not the leading H1 on the second run");
    }

    [TestMethod]
    public void SlugOf_FoldsIndexAndLowercases()
    {
        Assert.AreEqual("api", ApiStarlightWriter.SlugOf("index.md"));
        Assert.AreEqual("api/aprillz.mewui", ApiStarlightWriter.SlugOf("Aprillz.MewUI/index.md"));
        Assert.AreEqual("api/aprillz.mewui/aprillz.mewui/bindingpath-2", ApiStarlightWriter.SlugOf("Aprillz.MewUI\\Aprillz.MewUI\\BindingPath-2.md"));
        Assert.AreEqual("api/aprillz.mewui/aprillz.mewui.controls/gridviewrow/index-member", ApiStarlightWriter.SlugOf("Aprillz.MewUI/Aprillz.MewUI.Controls/GridViewRow/Index.md"));
    }

    [TestMethod]
    public void Run_KeepsIndexMemberApartFromTypePage()
    {
        WritePage("Aprillz.MewUI/Aprillz.MewUI.Controls/GridViewRow.md",
            "# GridViewRow class\n\nA row.\n\n| name | description |\n| --- | --- |\n| [Index](GridViewRow/Index.md) { get; } | The row index. |\n");
        WritePage("Aprillz.MewUI/Aprillz.MewUI.Controls/GridViewRow/Index.md",
            "# GridViewRow.Index property\n\nThe row index.\n\n* class [GridViewRow](../GridViewRow.md)\n");

        ApiStarlightWriter.Run(_root, SITE_BASE, null, new List<string>());

        var member = ReadPage("Aprillz.MewUI/Aprillz.MewUI.Controls/GridViewRow/Index.md");
        StringAssert.Contains(member, "\nslug: api/aprillz.mewui/aprillz.mewui.controls/gridviewrow/index-member\n");
        StringAssert.Contains(member, "[GridViewRow](/MewUI/api/aprillz.mewui/aprillz.mewui.controls/gridviewrow/)");
        var type = ReadPage("Aprillz.MewUI/Aprillz.MewUI.Controls/GridViewRow.md");
        StringAssert.Contains(type, "\nslug: api/aprillz.mewui/aprillz.mewui.controls/gridviewrow\n");
        StringAssert.Contains(type, "[Index](/MewUI/api/aprillz.mewui/aprillz.mewui.controls/gridviewrow/index-member/)");
    }

    private void WritePage(string relative, string content)
    {
        var path = Path.Combine(_root, relative);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content, new UTF8Encoding(false));
    }

    private string ReadPage(string relative) => File.ReadAllText(Path.Combine(_root, relative));

    private string HashTree()
    {
        var builder = new StringBuilder();
        foreach (var path in Directory.GetFiles(_root, "*", SearchOption.AllDirectories).OrderBy(static path => path, StringComparer.Ordinal))
        {
            builder.Append(Path.GetRelativePath(_root, path)).Append('=').Append(Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(path)))).Append('\n');
        }

        return builder.ToString();
    }

    private static int CountOccurrences(string text, string value)
    {
        var count = 0;
        for (var index = text.IndexOf(value, StringComparison.Ordinal); index >= 0; index = text.IndexOf(value, index + value.Length, StringComparison.Ordinal))
        {
            count++;
        }

        return count;
    }
}
