void StartResourceLoading()
{
    if (resourcesStarted)
    {
        return;
    }

    resourcesStarted = true;
    _ = LoadResourcesAsync();
}

async Task LoadResourcesAsync()
{
    async Task<(string Name, byte[]? Content, string? Error)> Download(string fileName)
    {
        string url = ResourceUrl(fileName);
        try
        {
            return (fileName, await http.GetByteArrayAsync(url), null);
        }
        catch
        {
            return (fileName, null, $"{fileName}: failed to download {url}");
        }
    }

    var downloads = await Task.WhenAll(GalleryResources.FileNames.Select(Download));

    void ApplyDownloads()
    {
        foreach (var download in downloads)
        {
            if (download.Content != null)
            {
                GalleryView.Resources.Apply(download.Name, download.Content);
            }
        }

        var failures = downloads.Where(x => x.Error != null).Select(x => x.Error!).ToList();
        int total = downloads.Length;
        int loaded = total - failures.Count;
        resourceStatus.Value = loaded switch
        {
            _ when loaded == total => "Resources: ready",
            0 => "Resources: failed",
            _ => $"Resources: partial ({loaded}/{total})"
        };

        resourceDetail.Value = failures.Count == 0
            ? "Resource detail: all downloads succeeded"
            : $"Resource detail: {string.Join(" | ", failures)}";

        if (loaded > 0 && failures.Count > 0 && !resourceStallToastShown)
        {
            resourceStallToastShown = true;
            window.ShowToast($"{resourceStatus.Value} - {string.Join(", ", failures.Select(x => x.Split(':')[0]))}");
        }
    }

    var dispatcher = Application.Current.Dispatcher;
    if (dispatcher != null)
    {
        dispatcher.BeginInvoke(DispatcherPriority.Normal, ApplyDownloads);
    }
    else
    {
        ApplyDownloads();
    }
}

